  await frame.waitForFunction(() => window.surdetPreviewDebug.runtime.queries.world.inspectStage().objects.find(object => object.target === 'rin:coat').pose.x > 525);
  assert.equal(await page.evaluate(() => [...window.surdetEditorDebug.state.scenes.values()].find(scene => scene.id === 'start').text), originalText);
  pass('real-pointer-drag-updates-only-visible-temporary-pose', { bounds });
  await page.screenshot({ path: path.join(output, 'stage-adjustment-1280x800.png'), fullPage: true });
